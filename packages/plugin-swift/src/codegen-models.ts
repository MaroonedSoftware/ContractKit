/**
 * Documentation for a declaration. Deprecation is noted in the doc comment rather than with
 * `@available(*, deprecated)`: the attribute on a model would make every generated client method
 * that names it warn, and on a field it would make the struct's own initializer warn.
 */
function declarationDoc(description: string | undefined, deprecated: boolean | undefined, indent: string): string[] {
    const parts: string[] = [];
    if (description) parts.push(description);
    if (deprecated) parts.push('- Warning: Deprecated in the contract.');
    if (parts.length === 0) return [];
    return docLines(parts.join('\n'), indent);
}

function fieldDoc(field: FieldNode, indent: string): string[] {
    return declarationDoc(field.description, field.deprecated, indent);
}

function uniqueName(name: string, used: Set<string>): string {
    if (!used.has(name)) {
        used.add(name);
        return name;
    }
    let n = 2;
    while (used.has(`${name}${n}`)) n++;
    used.add(`${name}${n}`);
    return `${name}${n}`;
}

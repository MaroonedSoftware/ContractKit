import { describe, expect, it } from 'vitest';
import { generateRuntimeSwift } from '../src/runtime.js';
import { generateJSONValueSwift } from '../src/runtime-json.js';
import { generateScalarsSwift } from '../src/runtime-scalars.js';

const RUNTIME = generateRuntimeSwift();
const SCALARS = generateScalarsSwift();
const JSON_VALUE = generateJSONValueSwift();

describe('every runtime file', () => {
    for (const [name, source] of [
        ['SdkRuntime.swift', RUNTIME],
        ['Scalars.swift', SCALARS],
        ['JSONValue.swift', JSON_VALUE],
    ] as const) {
        it(`${name} carries the generated banner and imports Foundation`, () => {
            expect(source.startsWith('// Auto-generated by @contractkit/plugin-swift. Do not edit manually.\nimport Foundation\n')).toBe(true);
        });

        it(`${name} leaves no unsubstituted template markers behind`, () => {
            expect(source).not.toContain('${');
            expect(source).not.toContain('undefined');
        });
    }
});

describe('SdkRuntime.swift', () => {
    it('guards the Linux networking import, which is where corelibs keeps URLSession', () => {
        expect(RUNTIME).toContain('#if canImport(FoundationNetworking)');
        expect(RUNTIME).toContain('import FoundationNetworking');
        expect(RUNTIME).toContain('#endif');
    });

    it('declares every type the generated code names', () => {
        for (const declaration of [
            'public struct SdkConfig',
            'public protocol HTTPTransport: Sendable',
            'public struct URLSessionTransport: HTTPTransport',
            'public struct SdkRequest',
            'public struct SdkResponse',
            'public struct SdkError: Error',
            'public struct MultipartPart',
            'public struct DynamicCodingKey: CodingKey',
            'public final class Indirect<Wrapped: Codable & Equatable & Sendable>: Codable, Equatable, Sendable',
            'public enum SdkJSON',
            'public final class SdkHttp: Sendable',
        ]) {
            expect(RUNTIME).toContain(declaration);
        }
    });

    it('exposes every helper a generated client calls', () => {
        for (const method of [
            'func execute(_ request: SdkRequest, expectStatuses: Set<Int> = [])',
            'func segment<T: Encodable>(_ value: T) throws -> String',
            'func addQuery<T: Encodable>(_ request: inout SdkRequest, _ value: T?) throws',
            'func addHeaders<T: Encodable>(_ request: inout SdkRequest, _ value: T?) throws',
            'func setJSONBody<T: Encodable>(_ request: inout SdkRequest, _ body: T, contentType: String) throws',
            'func setFormBody<T: Encodable>(_ request: inout SdkRequest, _ body: T, contentType: String) throws',
            'func setMultipartBody(_ request: inout SdkRequest, _ parts: [MultipartPart])',
            'func setTextBody(_ request: inout SdkRequest, _ body: String, contentType: String)',
            'func setBinaryBody(_ request: inout SdkRequest, _ body: Data, contentType: String)',
            'func decodeJSON<T: Decodable>(_ type: T.Type, from response: SdkResponse) throws -> T',
            'func requireHeader<T: HeaderDecodable>(_ response: SdkResponse, _ name: String, as type: T.Type) throws -> T',
            'func optionalHeader<T: HeaderDecodable>(_ response: SdkResponse, _ name: String, as type: T.Type) throws -> T?',
        ]) {
            expect(RUNTIME).toContain(method);
        }
    });

    it('gives a Sendable class only immutable storage, which is what lets it be Sendable at all', () => {
        const classes = [...RUNTIME.matchAll(/public final class [^\n]*Sendable \{\n([\s\S]*?)\n\}\n/g)];
        expect(classes.length).toBeGreaterThan(0);
        for (const [, body] of classes) {
            // A stored property sits at exactly one indent; anything deeper is a local inside a method.
            expect(body).not.toMatch(/^ {4}(public |private )?var \w+:/m);
        }
    });

    it('builds the JSON coders per call rather than storing them', () => {
        // Whether JSONEncoder is Sendable depends on the SDK version, so a stored one would make
        // SdkHttp's own Sendable conformance a compile error on some toolchains.
        expect(RUNTIME).toContain('public static func makeEncoder() -> JSONEncoder');
        expect(RUNTIME).not.toMatch(/let (encoder|decoder): JSON(Encoder|Decoder) =/);
    });

    it('reads a status the contract gives meaning to as a value, and raises on anything else', () => {
        expect(RUNTIME).toContain('if (200..<300).contains(response.status) || expectStatuses.contains(response.status) { return response }');
        expect(RUNTIME).toContain('throw SdkError(response: response, message:');
    });

    it('percent-encodes everything but the unreserved characters, so a value cannot add a path segment', () => {
        expect(RUNTIME).toContain('text.addingPercentEncoding(withAllowedCharacters: unreserved)');
        expect(RUNTIME).not.toContain('.urlPathAllowed');
    });

    it('runs the request through the completion-handler API, which every platform has', () => {
        expect(RUNTIME).toContain('withCheckedThrowingContinuation');
        expect(RUNTIME).toContain('session.dataTask(with: request)');
    });
});

describe('Scalars.swift', () => {
    it('declares a wrapper for each scalar Foundation cannot carry faithfully', () => {
        for (const name of ['BigIntValue', 'DecimalValue', 'LocalDate', 'LocalTime', 'IsoDuration']) {
            expect(SCALARS).toContain(`public struct ${name}: Codable, Hashable, Sendable, CustomStringConvertible, HeaderDecodable {`);
        }
    });

    it('conforms every type a response header may declare to HeaderDecodable', () => {
        for (const type of ['String', 'Int', 'Double', 'Bool', 'UUID', 'Date']) {
            expect(SCALARS).toContain(`extension ${type}: HeaderDecodable {`);
        }
    });

    it('reads a big integer written by any ContractKit client', () => {
        // The TypeScript SDK writes `123n`; the others write a digit string or a number.
        expect(SCALARS).toContain('rawValue = text.hasSuffix("n") ? String(text.dropLast()) : text');
        expect(SCALARS).toContain('try? container.decode(Int64.self)');
    });
});

describe('JSONValue.swift', () => {
    it('is an indirect enum over the six JSON shapes', () => {
        expect(JSON_VALUE).toContain('public indirect enum JSONValue: Codable, Equatable, Hashable, Sendable {');
        for (const shape of [
            'case null',
            'case bool(Bool)',
            'case number(Double)',
            'case string(String)',
            'case array([JSONValue])',
            'case object([String: JSONValue])',
        ]) {
            expect(JSON_VALUE).toContain(shape);
        }
    });

    it('flattens an object into query pairs, repeating a key per array element', () => {
        expect(JSON_VALUE).toContain('public var formPairs: [(name: String, value: String)] {');
        expect(JSON_VALUE).toContain('for key in fields.keys.sorted() {');
        expect(JSON_VALUE).toContain('if case .array(let items) = value {');
    });

    it('prints an integral number without a fractional part, as JSON does', () => {
        expect(JSON_VALUE).toContain('static func text(for number: Double) -> String {');
        expect(JSON_VALUE).toContain('return String(Int64(number))');
    });
});

import { resolve } from 'node:path';
import { buildModelIndex } from '../markdown/codegen.js';
import { computePubliclyReachableModels, groupEndpoints, groupModels } from '../../naming.js';
import { normalizeDir } from '../../layout.js';
import { generatedIndex, renderCategory } from './category.js';
import { renderEndpointPage, renderIndexPage, renderModelPage } from './pages.js';
import type { ModelPages, PagePath } from './pages.js';
import type { DocsTarget, DocusaurusConfig, GenerateInputs } from '../../target.js';
import type { ModelGroup } from '../../naming.js';
import type { PluginContext } from '@contractkit/core';

/**
 * The Docusaurus target.
 *
 * Emits a folder that drops into a stock `@docusaurus/preset-classic` `docs/` directory: one
 * Markdown page per endpoint and per documented model, plus the `_category_.json` files the
 * autogenerated sidebar reads. No OpenAPI spec and no extra Docusaurus plugin — the pages carry
 * their own content, so a site needs nothing installed to serve them.
 */

/** Resolved directory layout, so the emit code isn't re-deriving defaults inline. */
export interface DocusaurusLayout {
    /** Absolute docs root — the site's `docs/` directory. */
    baseDir: string;
    /** Endpoint page directory, relative to the docs root. */
    apiDir: string;
    /** Model page directory, relative to the docs root. */
    modelsDir: string;
}

export function resolveLayout(config: DocusaurusConfig, rootDir: string): DocusaurusLayout {
    const baseDir = resolve(rootDir, config.baseDir ?? 'docs');
    const apiDir = normalizeDir(config.apiDir ?? 'api-reference');
    const modelsDir = normalizeDir(config.modelsDir ?? (apiDir ? `${apiDir}/models` : 'models'));
    return { baseDir, apiDir, modelsDir };
}

/** Join docs-root-relative segments, tolerating an empty directory. */
function join(...segments: string[]): string {
    return segments.filter(s => s.length > 0).join('/');
}

/** Where each model's page lands, keyed by model name, for resolving cross-page links. */
function mapModelPages(groups: ModelGroup[], modelsDir: string): ModelPages {
    const pages = new Map<string, PagePath>();
    for (const group of groups) {
        for (const entry of group.models) {
            pages.set(entry.model.name, join(modelsDir, group.slug, entry.slug));
        }
    }
    return pages;
}

/** Emit the Docusaurus docs folder. */
export async function generateDocusaurus(inputs: GenerateInputs, ctx: PluginContext, config: DocusaurusConfig, rootDir: string): Promise<void> {
    const layout = resolveLayout(config, rootDir);
    const label = config.label ?? 'API Reference';
    const emit = (relPath: string, content: string, opts?: { ifAbsent: true }): void => ctx.emitFile(resolve(layout.baseDir, relPath), content, opts);

    const endpointGroups = groupEndpoints(inputs.opRoots, config.includeInternal);
    const modelGroups =
        config.modelPages === false ? [] : groupModels(inputs.contractRoots, computePubliclyReachableModels(inputs.opRoots, inputs.contractRoots));

    const modelPages = mapModelPages(modelGroups, layout.modelsDir);
    const modelIndex = buildModelIndex(inputs.contractRoots);

    // ── Endpoint pages, one folder per group ────────────────────
    endpointGroups.forEach((group, groupIndex) => {
        if (group.endpoints.length === 0) return;
        const dir = join(layout.apiDir, group.slug);
        emit(`${dir}/_category_.json`, renderCategory({ label: group.title, position: groupIndex + 1, link: generatedIndex(group.title) }));

        group.endpoints.forEach((entry, index) => {
            emit(`${dir}/${entry.slug}.md`, renderEndpointPage(entry, { position: index + 1, fromDir: dir, modelPages, modelIndex }));
        });
    });

    // ── Model pages: area-less ones sit flat, each area gets a folder ──
    const flatModels = modelGroups.find(g => g.area === undefined)?.models ?? [];
    const areaModelGroups = modelGroups.filter(g => g.area !== undefined && g.models.length > 0);

    if (modelGroups.some(g => g.models.length > 0)) {
        emit(
            `${join(layout.modelsDir)}/_category_.json`,
            renderCategory({ label: 'Models', position: endpointGroups.length + 1, link: generatedIndex('Models') }),
        );
    }

    flatModels.forEach((entry, index) => {
        emit(`${join(layout.modelsDir, entry.slug)}.md`, renderModelPage(entry, { position: index + 1, fromDir: layout.modelsDir, modelPages }));
    });

    // Positions continue past the flat models so an area folder sorts after them, matching the
    // "area-less first, then areas in first-seen order" ordering every other target uses.
    areaModelGroups.forEach((group, groupIndex) => {
        const dir = join(layout.modelsDir, group.slug);
        emit(
            `${dir}/_category_.json`,
            renderCategory({ label: group.title, position: flatModels.length + groupIndex + 1, link: generatedIndex(group.title) }),
        );
        group.models.forEach((entry, index) => {
            emit(`${dir}/${entry.slug}.md`, renderModelPage(entry, { position: index + 1, fromDir: dir, modelPages }));
        });
    });

    // ── The generated section itself ────────────────────────────
    // No `link`: `index.md` is the category's landing page by Docusaurus's own convention, which
    // is what makes the starter page worth handing to the user in the first place.
    if (layout.apiDir) {
        emit(`${layout.apiDir}/_category_.json`, renderCategory({ label, position: config.position }));
    }

    // Written once and then owned by the user. `ifAbsent` keeps it out of the manifest, so it is
    // never overwritten and never orphan-deleted.
    emit(join(layout.apiDir, 'index.md'), renderIndexPage(label), { ifAbsent: true });
}

const target: DocsTarget<DocusaurusConfig> = {
    name: 'docusaurus',
    generate: generateDocusaurus,
};

export default target;
